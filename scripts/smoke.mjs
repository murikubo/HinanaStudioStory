import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => localStorage.setItem('hinana:player:settings:v1', JSON.stringify({ speed: 0 })));
  await page.goto('http://127.0.0.1:5173');
  await page.getByRole('heading', { name: '프롤로그 · 다시 만난 여름', exact: true }).waitFor();
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/editor.png', fullPage: true });
  await page.getByRole('button', { name: '플레이 테스트', exact: true }).click();
  const modal = page.getByRole('dialog');
  await modal.getByRole('button', { name: '다음', exact: true }).click();
  await modal.getByRole('button', { name: '다음', exact: true }).click();
  await modal.getByRole('button', { name: '함께 추억을 만들자고 한다' }).click();
  await modal.getByText('좋아. 그럼 내일, 같은 시간에 여기서 만나!', { exact: true }).waitFor();
  await modal.getByRole('button', { name: '이야기 마치기' }).click();
  await modal.getByRole('region', { name: '제작 크레딧' }).waitFor();
  await modal.getByRole('button', { name: '편집기로 돌아가기' }).click();
  await page.getByRole('button', { name: '새 장면 만들기' }).click();
  await page.getByRole('textbox', { name: '장면 이름', exact: true }).fill('테스트 장면');
  await page.getByRole('textbox', { name: '대사 내용' }).fill('저장과 복원을 확인합니다.');
  await page.waitForTimeout(700);
  await page.reload();
  await page.getByRole('button', { name: /04 테스트 장면/ }).click();
  assert.equal(await page.getByRole('textbox', { name: '대사 내용' }).inputValue(), '저장과 복원을 확인합니다.');
  await page.getByRole('button', { name: '현재 장면 삭제' }).click();
  await page.getByRole('dialog', { name: '장면 삭제', exact: true }).getByRole('button', { name: '장면 삭제', exact: true }).click();
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await page.getByRole('button', { name: /04 테스트 장면/ }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '저장', exact: true }).click();
  const download = await downloadPromise;
  assert.ok(download.suggestedFilename().endsWith('.hinanastory'));
  await download.saveAs('test-results/smoke.hinanastory');
  await page.locator('input[type=file]').first().setInputFiles('test-results/smoke.hinanastory');
  await page.getByRole('status').filter({ hasText: '프로젝트를 열었습니다.' }).waitFor();
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
  await page.getByRole('combobox', { name: '배경 이미지' }).selectOption({ label: 'pixel.png' });
  await page.getByRole('button', { name: '선택지', exact: true }).click();
  await page.getByRole('textbox', { name: '선택 1 내용' }).fill('분기 테스트');
  await page.getByRole('combobox', { name: '이동할 장면' }).selectOption({ label: '02 · 하지 못한 말' });
  await page.getByRole('button', { name: '크게 미리보기' }).click();
  await modal.getByRole('button', { name: '분기 테스트' }).click();
  await modal.getByText('사실은… 너에게 꼭 하고 싶은 말이 있었어.', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('PASS: edit, branch playback, autosave recovery, undo, file export/import, image import, choice editing, escape; no renderer errors');
} finally { await browser.close(); }
